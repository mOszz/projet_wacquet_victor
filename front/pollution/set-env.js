// Runs before `ng build` (see package.json).
// On Render, API_HOST holds the API service name (e.g. "pollution-api-xxxx", see render.yaml):
// environment.ts is then rewritten to call the deployed API instead of the mock.
// Without API_HOST (local build), environment.ts is left untouched.
const fs = require('fs');
const path = require('path');

const host = process.env.API_HOST?.trim();

if (!host) {
  console.log('[set-env] API_HOST not set: environment.ts unchanged.');
} else {
  // Render may give a bare service name or a full host name.
  const domain = host.includes('.') ? host : `${host}.onrender.com`;
  const apiUrl = `https://${domain}/api`;

  const content = `// Generated by set-env.js during the Render build.
export const environment = {
  production: true,
  apiUrl: '${apiUrl}',
  useMockApi: false,
};
`;

  fs.writeFileSync(path.join(__dirname, 'src/environments/environment.ts'), content);
  console.log(`[set-env] environment.ts -> apiUrl = ${apiUrl}`);
}
